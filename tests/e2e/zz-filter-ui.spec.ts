import { test, expect } from "@playwright/test";
test.use({ storageState: "test-results/admin-state.json" });
test("filter popover floats without shifting table and preserves URL context", async ({ page }) => {
  await page.goto("/inbox?pageSize=10");
  await expect(page.locator(".table-panel tbody tr")).toHaveCount(2);
  await expect(page.getByText("Inbox privat", { exact: true })).toHaveCount(0);
  await expect(page.locator(".inbox-line-chart .highcharts-container")).toHaveCount(1);
  const rows = page.locator(".table-panel tbody");
  const trigger = page.getByRole("button", { name: "Filter", exact: true });
  await trigger.scrollIntoViewIfNeeded();
  const before = await rows.evaluate((element) => element.getBoundingClientRect().top + scrollY);
  await trigger.click();
  const popover = page.getByRole("dialog", { name: "Filter feedback" });
  await expect(popover).toBeVisible();
  const after = await rows.evaluate((element) => element.getBoundingClientRect().top + scrollY);
  expect(Math.abs(after - before)).toBeLessThan(1);
  await popover.getByRole("radio", { name: "Saran", exact: true }).check();
  expect(new URL(page.url()).searchParams.get("type")).toBeNull();
  await popover.getByRole("button", { name: "Terapkan" }).click();
  await expect(page).toHaveURL(/type=SUGGESTION/);
  expect(new URL(page.url()).searchParams.get("pageSize")).toBe("10");
  const activeTrigger = page.getByRole("button", { name: "Filter (1)", exact: true });
  await activeTrigger.click();
  await page.keyboard.press("Escape");
  await expect(popover).toHaveCount(0);
  await expect(activeTrigger).toBeFocused();
  await activeTrigger.click();
  await page.getByRole("heading", { name: "Feedback pengunjung" }).click();
  await expect(popover).toHaveCount(0);
  await activeTrigger.click();
  await page.keyboard.press("Shift+Tab");
  await expect(popover).toHaveCount(0);
  await expect(activeTrigger).toBeFocused();
  await activeTrigger.click();
  await popover.getByRole("button", { name: "Reset filter" }).click();
  await expect(page.locator(".table-panel tbody tr")).toHaveCount(2);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "Filter", exact: true }).click();
  await expect(popover).toBeVisible();
  const box = await popover.boundingBox();
  expect(box!.x).toBeGreaterThanOrEqual(0);
  expect(box!.x + box!.width).toBeLessThanOrEqual(390);
  expect(box!.y + box!.height).toBeLessThanOrEqual(845);
  await page.screenshot({ path: "test-results/inbox-filter-mobile.png", fullPage: true });
  await page.keyboard.press("Escape");
  await page.setViewportSize({ width: 1440, height: 1000 });
  const label = page.locator(".pagination .page-size");
  const sizeBox = await label.boundingBox();
  const footer = await page.locator(".pagination").boundingBox();
  expect(footer!.x + footer!.width - (sizeBox!.x + sizeBox!.width)).toBeLessThan(35);
});
