test("widget key rotation requires confirmation and retires old key without deleting reports", async ({ page, browser }) => {
  await page.goto("/settings");
  await page.getByRole("link", { name: /^Installation code for / }).first().click();
  const oldKey = (await (await page.request.get("/api/admin/site")).json()).publicKey;
  await expect(page.getByLabel("Key aktif", { exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Perbarui kode pemasangan", exact: true })).toBeHidden();
  await page.locator("summary").filter({ hasText: "Pengaturan lanjutan" }).click();
  const before = await (await page.request.get("/api/admin/feedback")).json();
  const anonymous = await browser.newContext({ storageState: { cookies: [], origins: [] } });
  expect((await anonymous.request.post("http://localhost:3100/api/admin/site/key", { headers: { Origin: "http://localhost:3100" }, data: { confirm: true, expectedKey: oldKey } })).status()).toBe(401);
  expect((await page.request.post("/api/admin/site/key", { headers: { Origin: "https://evil.example" }, data: { confirm: true, expectedKey: oldKey } })).status()).toBe(403);
  expect((await page.request.post("/api/admin/site/key", { headers: { Origin: "http://localhost:3100" }, data: { confirm: false, expectedKey: oldKey } })).status()).toBe(400);
  await page.getByRole("button", { name: "Perbarui kode pemasangan", exact: true }).click();
  const confirmation = page.getByRole("dialog", { name: "Perbarui kode pemasangan?" });
  await expect(confirmation).toBeVisible();
  await confirmation.getByRole("button", { name: "Batal", exact: true }).click();
  expect((await (await page.request.get("/api/admin/site")).json()).publicKey).toBe(oldKey);
  await page.getByRole("button", { name: "Perbarui kode pemasangan", exact: true }).click();
  await confirmation.getByRole("button", { name: "Perbarui sekarang", exact: true }).click();
  await expect(confirmation).toBeHidden();
  const newKey = (await (await page.request.get("/api/admin/site")).json()).publicKey;
  expect(newKey).not.toBe(oldKey);
  expect(newKey.length).toBe(32);
  await expect(page.locator("pre code")).toContainText(newKey);
  await page.reload(); await expect(page.locator("pre code")).toContainText(newKey);
  expect((await page.request.post("/api/admin/site/key", { headers: { Origin: "http://localhost:3100" }, data: { confirm: true, expectedKey: oldKey } })).status()).toBe(409);
  expect((await anonymous.request.get("http://localhost:3100/widget/" + oldKey)).status()).toBe(404);
  expect((await anonymous.request.get("http://localhost:3100/widget/" + newKey)).status()).toBe(200);
  const testEnvironment = parse(await readFile(".env.test"));
  if (new URL(testEnvironment.DATABASE_URL).pathname !== "/ureport_test") throw new Error("Rate limit fixture requires isolated test database.");
  const pool = new pg.Pool({ connectionString: testEnvironment.DATABASE_URL });
  try { await pool.query('DELETE FROM "RateBucket" WHERE key LIKE $1', ["submit:%"]); } finally { await pool.end(); }
  const retiredSubmit = await anonymous.request.post("http://localhost:3100/api/feedback", { multipart: { siteKey: oldKey, submissionId: crypto.randomUUID(), type: "ISSUE", message: "Retired key must not accept" } });
  expect(retiredSubmit.status()).toBe(404);
  const after = await (await page.request.get("/api/admin/feedback")).json(); expect(after.total).toBe(before.total);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: "test-results/widget-key-mobile.png", fullPage: true });
  await anonymous.close();
});
