test("website list and add form align side-by-side on desktop and stack on mobile", async ({ page }) => {
  test.setTimeout(30000);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("/settings");
  await expect(page.locator(".website-table")).toBeVisible();
  const list = await page.locator(".websites-list-column").boundingBox();
  const form = await page.locator(".website-add").boundingBox();
  expect(list).not.toBeNull();
  expect(form!.x).toBeGreaterThan(list!.x + list!.width);
  expect(Math.abs(form!.y - list!.y)).toBeLessThan(2);
  expect(list!.width).toBeGreaterThan(form!.width);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: "test-results/websites-two-columns-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  const mobileList = await page.locator(".websites-list-column").boundingBox();
  const mobileForm = await page.locator(".website-add").boundingBox();
  expect(mobileForm!.y).toBeGreaterThanOrEqual(mobileList!.y + mobileList!.height);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: "test-results/websites-two-columns-mobile.png", fullPage: true });
});
